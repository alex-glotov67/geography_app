import { plural, tasksWord } from './plural'

describe('plural', () => {
  it.each([
    [1, 'урок'], [2, 'уроки'], [4, 'уроки'], [5, 'уроків'], [11, 'уроків'], [12, 'уроків'],
    [14, 'уроків'], [21, 'урок'], [22, 'уроки'], [25, 'уроків'], [101, 'урок'], [111, 'уроків'],
  ])('%i → %s', (n, w) => {
    expect(plural(n, 'урок', 'уроки', 'уроків')).toBe(w)
  })
  it('завдання / завдань', () => {
    expect(tasksWord(1)).toBe('1 завдання')
    expect(tasksWord(3)).toBe('3 завдання')
    expect(tasksWord(6)).toBe('6 завдань')
  })
})
